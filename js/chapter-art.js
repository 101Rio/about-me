    function brushes(context) {
        function rect(x, y, w, h, color) {
            context.fillStyle = color;
            context.fillRect(x, y, w, h);
        }

        function line(from, to, color) {
            let [x, y] = from;
            const [endX, endY] = to;
            const dx = Math.abs(endX - x);
            const dy = -Math.abs(endY - y);
            const stepX = x < endX ? 1 : -1;
            const stepY = y < endY ? 1 : -1;
            let error = dx + dy;
            while (true) {
                rect(x, y, 1, 1, color);
                if (x === endX && y === endY) break;
                const twiceError = 2 * error;
                if (twiceError >= dy) { error += dy; x += stepX; }
                if (twiceError <= dx) { error += dx; y += stepY; }
            }
        }

        function path(points, color) {
            for (let i = 1; i < points.length; i++) line(points[i - 1], points[i], color);
        }

        function shape(points, color) {
            const ys = points.map(point => point[1]);
            const bottom = Math.max(...ys);
            for (let y = Math.min(...ys); y < bottom; y++) {
                const scanY = y + 0.5;
                const hits = [];
                for (let i = 0; i < points.length; i++) {
                    const [x1, y1] = points[i];
                    const [x2, y2] = points[(i + 1) % points.length];
                    if ((y1 > scanY) !== (y2 > scanY)) {
                        hits.push(x1 + (scanY - y1) * (x2 - x1) / (y2 - y1));
                    }
                }
                hits.sort((a, b) => a - b);
                for (let i = 0; i + 1 < hits.length; i += 2) {
                    const start = Math.ceil(hits[i] - 0.5);
                    const end = Math.ceil(hits[i + 1] - 0.5);
                    rect(start, y, end - start, 1, color);
                }
            }
        }

        function oval(cx, cy, rx, ry, color) {
            for (let row = -ry; row <= ry; row++) {
                const span = Math.round(rx * Math.sqrt(1 - (row / ry) ** 2));
                rect(cx - span, cy + row, span * 2 + 1, 1, color);
            }
        }
        return { rect, line, path, shape, oval };
    }

